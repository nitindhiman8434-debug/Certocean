export function getCourseBySlug(slug: string) {
  return courses.find((c) => c.slug === slug);
}

export function getCoursesByCategory(categorySlug: string) {
  return courses.filter((c) => c.categorySlug === categorySlug);
}

export function getPopularCourses() {
  return courses.filter((c) => c.popular);
}

export function getRelatedCourses(course: Course) {
  return course.relatedCourseSlugs
    .map((s) => getCourseBySlug(s))
    .filter((c): c is Course => Boolean(c));
}
